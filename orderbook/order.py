"""
orderbook/order.py

============================================================
L3 Order Definition
============================================================

职责：

    定义 L3 订单对象。


数据来源：

    Databento MBO


一个 Order 对应：

    一个真实挂单。


============================================================


核心字段：

    order_id

        订单唯一ID


    price

        订单价格


    side

        买/卖方向


    size

        当前剩余数量


    sequence

        Databento 原始消息序号


    timestamp

        订单进入时间


============================================================


订单簿规则：

    Price Priority

        外层价格排序


    FIFO

        同价格按照 sequence 排序


============================================================


不负责：

    - 撮合

    - 成交

    - 策略

    - 风控


============================================================

"""


from dataclasses import dataclass
from enum import Enum
from typing import Optional


# ============================================================
# 统一引用 MarketEvent 定义
#
# 重要：
#
# 整个系统只能存在一个 OrderSide
#
# 来源：
#
# core.event
#
# Databento MBO:
#
# B = Bid
# A = Ask
#
# ============================================================

from core.event import OrderSide



# ============================================================
# Order Status
# ============================================================

class OrderStatus(Enum):
    """
    订单状态。
    """

    # 当前有效挂单
    ACTIVE = "ACTIVE"


    # 已完全成交
    FILLED = "FILLED"


    # 已取消
    CANCELLED = "CANCELLED"


    # 已失效
    REMOVED = "REMOVED"





# ============================================================
# Order
# ============================================================

@dataclass(slots=True)
class Order:
    """
    L3 单个订单。


    对应：

        Databento MBO Order


    ========================================================


    示例：


        order_id = 10001

        side = BID

        price = 6959750000000

        size = 5


    表示：

        Bid价格6959.75

        数量5


    ========================================================

    """


    # ========================================================
    # 交易所订单ID
    # ========================================================

    order_id: int



    # ========================================================
    # 买卖方向
    # ========================================================

    side: OrderSide



    # ========================================================
    # 价格
    #
    # Databento:
    #
    # 使用整数价格
    #
    # ========================================================

    price: int



    # ========================================================
    # 剩余数量
    # ========================================================

    size: int



    # ========================================================
    # 原始事件序号
    #
    # FIFO核心
    #
    # ========================================================

    sequence: int



    # ========================================================
    # 交易所事件时间
    #
    # 纳秒
    #
    # ========================================================

    ts_event: int



    # ========================================================
    # 状态
    # ========================================================

    status: OrderStatus = OrderStatus.ACTIVE



    # ========================================================
    # 已成交数量
    # ========================================================

    filled_size: int = 0



    # ========================================================
    # 创建时原始数量
    # ========================================================

    original_size: Optional[int] = None



    def __post_init__(self):
        """
        初始化处理。
        """

        if self.original_size is None:

            self.original_size = self.size




    # ========================================================
    # 修改数量
    # ========================================================

    def modify(
        self,
        new_size: int
    ):
        """
        Modify Order。

        对应：

            Databento Action = M

        """

        self.size = new_size


        if self.size <= 0:

            self.status = OrderStatus.REMOVED





    # ========================================================
    # 成交
    # ========================================================

    def fill(
        self,
        quantity: int
    ):
        """
        记录成交。


        注意：

        不代表OrderBook更新。


        """

        self.filled_size += quantity


        self.size -= quantity



        if self.size <= 0:

            self.size = 0

            self.status = OrderStatus.FILLED





    # ========================================================
    # Cancel
    # ========================================================

    def cancel(
        self
    ):
        """
        取消订单。

        对应：

            Databento Action = C

        """

        self.status = OrderStatus.CANCELLED





    # ========================================================
    # 是否有效
    # ========================================================

    def is_active(
        self
    ) -> bool:
        """
        是否仍在盘口。
        """

        return (

            self.status

            ==

            OrderStatus.ACTIVE

            and

            self.size > 0

        )





    # ========================================================
    # 剩余数量
    # ========================================================

    def remaining(
        self
    ) -> int:
        """
        返回剩余数量。
        """

        return self.size